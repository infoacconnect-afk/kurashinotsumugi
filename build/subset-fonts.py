#!/usr/bin/env python3
"""Regenerate checked-in WOFF2 subsets from the existing licensed fonts.

Maintenance only, not a Netlify build dependency:
  python -m pip install fonttools==4.61.1 Brotli==1.2.1
  python build/subset-fonts.py
All original Unicode coverage is retained, including characters not used by
today's pages. New CMS articles never require running this script.
"""
from pathlib import Path
from hashlib import sha256
from io import BytesIO
import json
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / 'assets/fonts'
OUT = FONTS / 'subsets'
FACES = [
    ('Noto Sans JP', 400, 'a488fa408fd4b608.woff2', True),
    ('Noto Sans JP', 500, 'a797a2c2fc4cdd23.woff2', True),
    ('Noto Sans JP', 700, 'a837e86a4106faa5.woff2', False),
    ('Zen Maru Gothic', 500, 'ef2c247b02d01876.woff2', True),
    ('Zen Maru Gothic', 700, '939b6dcbb2e6335f.woff2', False),
]


def unicode_ranges(points):
    runs = []
    for point in sorted(points):
        if runs and point == runs[-1][1] + 1:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in runs)


def verify(original, generated, points):
    """Check coverage, font metrics, glyph outlines and advance widths."""
    oldmap, newmap = original.getBestCmap(), generated.getBestCmap()
    # Layout closure may retain an extra cmap alias (for example U+2039).
    # CSS unicode-range, rather than these aliases, defines each shard's range.
    assert set(points) <= set(newmap), 'Subset Unicode coverage changed'
    for table, attrs in {
        'head': ['unitsPerEm'],
        'hhea': ['ascent', 'descent', 'lineGap'],
        'OS/2': ['sTypoAscender', 'sTypoDescender', 'sTypoLineGap',
                 'usWinAscent', 'usWinDescent', 'usWeightClass'],
    }.items():
        for attr in attrs:
            assert getattr(original[table], attr) == getattr(generated[table], attr)
    for cp in points:
        a, b = oldmap[cp], newmap[cp]
        assert original['hmtx'][a] == generated['hmtx'][b], hex(cp)
        assert original['vmtx'][a] == generated['vmtx'][b], hex(cp)
        assert original['glyf'][a].getCoordinates(original['glyf']) == generated['glyf'][b].getCoordinates(generated['glyf']), hex(cp)


def main():
    # Shared core stays identical between pages, so navigation reuses the cache.
    # Future/new characters are served by disjoint remainder shards below.
    sources = sorted(ROOT.glob('*.html')) + sorted((ROOT / 'assets').glob('*.js'))
    core = set(range(0x20, 0x100)) | set(range(0x3000, 0x3100)) | set(range(0xFF00, 0xFFF0))
    for path in sources:
        core.update(map(ord, path.read_text()))
    OUT.mkdir(exist_ok=True)
    css = ['/* Generated by build/subset-fonts.py. Keep the original font licenses. */']
    manifest = {'faces': [], 'preloads': []}
    keep = set()
    for family, weight, source, preload in FACES:
        original = TTFont(FONTS / source, recalcTimestamp=False)
        coverage = set(original.getBestCmap())
        common = sorted(coverage & core)
        rest = sorted(coverage - core)
        groups = [common] + [rest[i:i + 1024] for i in range(0, len(rest), 1024)]
        face = {'family': family, 'weight': weight, 'source': source,
                'sourceBytes': (FONTS / source).stat().st_size, 'subsets': []}
        served = set()
        for i, points in enumerate(groups):
            font = TTFont(FONTS / source, recalcTimestamp=False)
            options = subset.Options()
            options.layout_features = ['*']
            options.name_IDs = ['*']
            options.name_legacy = True
            options.name_languages = ['*']
            options.glyph_names = True
            options.recalc_timestamp = False
            worker = subset.Subsetter(options=options)
            worker.populate(unicodes=points)
            worker.subset(font)
            font.flavor = 'woff2'
            buf = BytesIO()
            font.save(buf)
            payload = buf.getvalue()
            verified = TTFont(BytesIO(payload))
            verify(original, verified, points)
            assert not served.intersection(points)
            served.update(points)
            filename = sha256(payload).hexdigest()[:20] + '.woff2'
            (OUT / filename).write_bytes(payload)
            keep.add(filename)
            ranges = unicode_ranges(points)
            css.append(f"@font-face {{\n  font-family: '{family}';\n  font-style: normal;\n  font-weight: {weight};\n  font-display: block;\n  src: url(fonts/subsets/{filename}) format('woff2');\n  unicode-range: {ranges};\n}}")
            face['subsets'].append({'file': filename, 'bytes': len(payload), 'range': ranges, 'core': i == 0})
            if i == 0 and preload:
                manifest['preloads'].append('/assets/fonts/subsets/' + filename)
            font.close()
            verified.close()
        assert served == coverage, 'An original character was lost'
        original.close()
        manifest['faces'].append(face)
        print(f"{family} {weight}: core {face['subsets'][0]['bytes']:,} / original {face['sourceBytes']:,} bytes; {len(groups)} subsets; complete coverage verified", flush=True)
    for path in OUT.glob('*.woff2'):
        if path.name not in keep:
            path.unlink()
    (ROOT / 'assets/fonts-local.css').write_text('\n'.join(css) + '\n')
    (FONTS / 'subsets-manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')


if __name__ == '__main__':
    main()
